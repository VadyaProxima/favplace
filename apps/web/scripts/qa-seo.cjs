const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const base = process.env.SEO_QA_BASE || 'http://localhost:3003'
const canonicalOrigin = 'https://mestometal.ru'
const guide = '/guide/topographic-rings', ruGuide = '/ru/guide/topographic-rings'

;(async () => {
	const browser = await chromium.launch({ channel: 'chrome', headless: true })
	try {
		// Verify the actual server HTML, with no client rendering or local storage.
		const context = await browser.newContext({ javaScriptEnabled: false })
		const page = await context.newPage()
		const titles = new Set()
		for (const path of ['/', '/create', '/credits', guide, ruGuide]) {
			const response = await page.goto(base + path, { waitUntil: 'domcontentloaded' })
			assert.equal(response.status(), 200, path)
			assert.equal(new URL(await page.locator('link[rel="canonical"]').getAttribute('href')).href, canonicalOrigin + path)
			assert.equal(await page.locator('h1').count(), 1, `${path}: one readable heading without JS`)
			assert.ok((await page.locator('body').innerText()).length > 180)
			assert.ok((await page.locator('meta[name="description"]').getAttribute('content')).length > 50)
			assert.equal(new URL(await page.locator('meta[property="og:url"]').getAttribute('content')).href, canonicalOrigin + path)
			assert.equal(await page.locator('meta[property="og:image"]').getAttribute('content'), canonicalOrigin + '/social-image')
			titles.add(await page.title())
			if (path.includes('/guide/')) {
				for (const [language, target] of [['en', guide], ['ru', ruGuide], ['x-default', guide]]) {
					assert.equal(await page.locator(`link[rel="alternate"][hreflang="${language}"]`).getAttribute('href'), canonicalOrigin + target)
				}
				assert.equal(await page.locator('main').getAttribute('lang'), path === ruGuide ? 'ru' : 'en')
				assert.equal(await page.locator('tbody tr').count(), 3)
				assert.match(await page.locator('tbody').innerText(), path === ruGuide ? /16\s400/ : /\$210/)
				const graph = JSON.parse(await page.locator('script[type="application/ld+json"]').textContent())['@graph']
				assert.equal(graph.find(node => node['@type'] === 'Article').inLanguage, path === ruGuide ? 'ru' : 'en')
			}
		}
		assert.equal(titles.size, 5, 'Unique page titles')
		await page.goto(base)
		assert.equal(await page.locator('#questions details').count(), 7)
		const schema = JSON.parse(await page.locator('script[type="application/ld+json"]').textContent())
		const product = schema['@graph'].find(node => node['@type'] === 'Product')
		assert.deepEqual(product.offers.map(offer => [offer.price, offer.priceCurrency]), [[210, 'USD'], [220, 'USD'], [230, 'USD']])
		assert.ok(!product.aggregateRating && !product.review)
		await page.goto(base + '/create?lat=-49.3748&lng=-72.79745&b=57&r=20000&h=2.23')
		assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'), canonicalOrigin + '/create')
		const admin = await page.goto(base + '/admin')
		assert.match(admin.headers()['x-robots-tag'], /noindex/)
		assert.match(await page.locator('meta[name="robots"]').getAttribute('content'), /noindex/)
		const missing = await page.goto(base + '/seo-check-missing-page')
		assert.equal(missing.status(), 404)
		assert.ok((await page.locator('meta[name="robots"]').all()).length > 0)
		assert.ok((await page.locator('meta[name="robots"]').evaluateAll(nodes => nodes.map(node => node.content))).some(content => content.includes('noindex')))
		const robots = await context.request.get(base + '/robots.txt')
		assert.equal(robots.status(), 200)
		const rules = await robots.text()
		assert.match(rules, /User-Agent: \*/i)
		assert.match(rules, /Allow: \/\s/)
		assert.match(rules, /Sitemap: https:\/\/mestometal.ru\/sitemap.xml/)
		assert.ok(!rules.includes('Disallow: /\n'))
		const sitemap = await context.request.get(base + '/sitemap.xml')
		const xml = await sitemap.text()
		assert.equal(sitemap.status(), 200)
		assert.equal((xml.match(/<loc>/g) || []).length, 5)
		assert.ok(!/localhost|\/admin|create-mapbox|create-terrarium|lastmod/.test(xml))
		const social = await context.request.get(base + '/social-image')
		assert.equal(social.status(), 200)
		assert.match(social.headers()['content-type'], /image\/png/)
		const png = await social.body()
		assert.equal(png.readUInt32BE(16), 1200)
		assert.equal(png.readUInt32BE(20), 630)
		console.log('PASS: server HTML, unique metadata, canonical shared URLs, JSON-LD/prices, bilingual guides/hreflang, robots/sitemap, PNG social preview and noindex/404')
		await context.close()

		const live = await browser.newContext({ viewport: { width: 390, height: 844 } })
		await live.addInitScript(() => localStorage.setItem('favplace:preferences', JSON.stringify({ language: 'ru', theme: 'dark' })))
		const mobile = await live.newPage(), errors = []
		mobile.on('pageerror', error => errors.push(error.message))
		await mobile.goto(base + guide, { waitUntil: 'networkidle' })
		assert.match(await mobile.title(), /Topographic Rings:/)
		assert.equal(await mobile.locator('html').getAttribute('lang'), 'en')
		await mobile.getByRole('link', { name: 'Русский', exact: true }).click()
		await mobile.waitForURL('**' + ruGuide)
		await mobile.waitForFunction(() => document.documentElement.lang === 'ru')
		assert.match(await mobile.title(), /Кольца с рельефом:/)
		assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
		await mobile.screenshot({ path: process.env.TEMP + '/favplace-seo-guide-mobile.png', fullPage: true })
		await mobile.goto(base, { waitUntil: 'domcontentloaded' })
		await mobile.getByRole('button', { name: 'Switch to English', exact: true }).waitFor()
		await mobile.waitForFunction(() => document.title.includes('Кольца с рельефом гор'))
		const ruSchema = JSON.parse(await mobile.locator('script[type="application/ld+json"]').textContent())
		assert.equal(ruSchema['@graph'].find(node => node['@type'] === 'Product').offers[0].priceCurrency, 'RUB')
		await mobile.locator('#questions summary').first().click()
		assert.ok(await mobile.locator('#questions details').first().getAttribute('open') !== null)
		assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
		await mobile.getByRole('button', { name: 'Switch to English', exact: true }).click()
		await mobile.waitForFunction(() => document.title.includes('Custom Topographic Silver Rings'))
		assert.match(await mobile.locator('meta[name="description"]').getAttribute('content'), /From \$210/)
		assert.deepEqual(errors, [])
		console.log('PASS: guide language survives saved preferences/client navigation; mobile FAQ and RU/EN metadata/schema match visible content; no browser exceptions')
		await live.close()
	} finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
